#!/bin/bash

# 1. ตรวจสอบว่าผู้ใช้พิมพ์อะไรต่อท้ายมาไหม
if [ $# -eq 0 ]; then
    # ถ้าจำนวนคำที่พิมพ์ต่อท้าย ($#) เท่ากับ 0 ให้พิมพ์เตือน
    echo "No arguments supplied"
else
    # 2. ถ้ามีคำต่อท้าย ให้หยิบคำเหล่านั้นมาทำงานทีละคำ
    for name in "$@"
    do
        # 3. สร้างโฟลเดอร์ โดยเอา 'ex' ไปวางหน้าชื่อนั้นๆ
        mkdir "ex$name"
    done
fi
